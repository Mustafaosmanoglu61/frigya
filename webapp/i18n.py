def translate(text, lang: str = DEFAULT_LANG) -> str:
    """lang 'en' ise sözlükten çevir; yoksa/tr ise orijinali döndür."""
    if lang == "en":
        return TRANSLATIONS.get(text, text)
    return text


def request_lang(request) -> str:
    """İsteğin oturumundaki dil; oturum yoksa varsayılan."""
    try:
        return normalize_lang(request.session.get("lang"))
    except Exception:
        return DEFAULT_LANG


def tx(request, text: str, **kwargs) -> str:
    """Sunucu mesajını isteğin diline çevirir, {yer tutucu}ları doldurur."""
    out = translate(text, request_lang(request))
    return out.format(**kwargs) if kwargs else out


def tx_q(request, text: str, **kwargs) -> str:
    """tx + URL kodlama: yönlendirme adresindeki ?msg= / ?error= değerleri için."""
    return quote(tx(request, text, **kwargs))
